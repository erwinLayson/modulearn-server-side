-- schools
CREATE TABLE IF NOT EXISTS `schools` (
  `id` binary(16) NOT NULL,
  `school_id` bigint(20) NOT NULL,
  `school_name` varchar(255) NOT NULL,
  `school_level` int(11) NOT NULL,
  `academic_system` enum('quarter','semester') NOT NULL DEFAULT 'quarter',
  `period_count` int(11) NOT NULL DEFAULT 4,
  `academic_config_completed` tinyint(1) NOT NULL DEFAULT 0,
  `school_email` varchar(255) NOT NULL,
  `address` varchar(255) NOT NULL,
  `region` varchar(255) NOT NULL,
  `province` varchar(255) NOT NULL,
  `city` varchar(255) NOT NULL,
  `contact_number` varchar(255) NOT NULL,
  `school_logo` varchar(255) NOT NULL,
  `school_admin` varchar(255) NOT NULL,
  `registered_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NULL DEFAULT NULL ON UPDATE current_timestamp(),
  `admin_id` binary(16) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `school_email` (`school_email`),
  KEY `fk_admin_id` (`admin_id`),
  KEY `idx_schools_school_id` (`school_id`),
  CONSTRAINT `fk_admin_id` FOREIGN KEY (`admin_id`) REFERENCES `school_admins` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
