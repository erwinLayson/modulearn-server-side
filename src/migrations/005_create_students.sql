-- students
CREATE TABLE IF NOT EXISTS `students` (
  `id` binary(16) NOT NULL,
  `first_name` varchar(255) NOT NULL,
  `middle_name` varchar(255) DEFAULT '',
  `last_name` varchar(255) NOT NULL,
  `extension_name` varchar(50) DEFAULT '',
  `email` varchar(255) NOT NULL,
  `password` varchar(255) NOT NULL,
  `school_id` bigint(20) NOT NULL,
  `lrn` varchar(20) DEFAULT '',
  `date_of_birth` date DEFAULT NULL,
  `place_of_birth` varchar(255) DEFAULT '',
  `sex` enum('male','female') NOT NULL DEFAULT 'male',
  `nationality` varchar(100) DEFAULT 'Filipino',
  `region` varchar(255) DEFAULT '',
  `province` varchar(255) DEFAULT '',
  `city_municipality` varchar(255) DEFAULT '',
  `barangay` varchar(255) DEFAULT '',
  `purok_street` varchar(255) DEFAULT '',
  `contact_number` varchar(255) DEFAULT NULL,
  `created_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_at` timestamp NULL DEFAULT NULL ON UPDATE current_timestamp(),
  `admin_id` binary(16) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_students_email_school` (`email`,`school_id`),
  KEY `idx_students_school_id` (`school_id`),
  CONSTRAINT `fk_students_school_id` FOREIGN KEY (`school_id`) REFERENCES `schools` (`school_id`),
  CONSTRAINT `fk_students_user_id` FOREIGN KEY (`id`) REFERENCES `users` (`id`) ON DELETE CASCADE ON UPDATE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
