-- period_finalizations
CREATE TABLE IF NOT EXISTS `period_finalizations` (
  `id` bigint(20) NOT NULL AUTO_INCREMENT,
  `school_id` bigint(20) NOT NULL,
  `school_year_id` bigint(20) NOT NULL,
  `period_id` bigint(20) DEFAULT NULL,
  `class_id` binary(16) NOT NULL,
  `subject_id` binary(16) NOT NULL,
  `student_id` binary(16) NOT NULL,
  `final_grade` decimal(5,2) DEFAULT NULL,
  `finalized_by` binary(16) NOT NULL,
  `finalized_at` timestamp NOT NULL DEFAULT current_timestamp(),
  `updated_by` binary(16) DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  `correction_reason` varchar(500) DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_period_finalizations` (`period_id`,`class_id`,`subject_id`,`student_id`),
  KEY `idx_pf_student` (`student_id`),
  KEY `idx_pf_class_subject` (`class_id`,`subject_id`),
  KEY `fk_pf_school` (`school_id`),
  KEY `fk_pf_school_year` (`school_year_id`),
  KEY `fk_pf_subject` (`subject_id`),
  KEY `fk_pf_finalized_by` (`finalized_by`),
  CONSTRAINT `fk_pf_class` FOREIGN KEY (`class_id`) REFERENCES `classes` (`id`),
  CONSTRAINT `fk_pf_finalized_by` FOREIGN KEY (`finalized_by`) REFERENCES `users` (`id`),
  CONSTRAINT `fk_pf_period` FOREIGN KEY (`period_id`) REFERENCES `academic_periods` (`id`),
  CONSTRAINT `fk_pf_school` FOREIGN KEY (`school_id`) REFERENCES `schools` (`school_id`) ON DELETE CASCADE,
  CONSTRAINT `fk_pf_school_year` FOREIGN KEY (`school_year_id`) REFERENCES `school_years` (`id`),
  CONSTRAINT `fk_pf_student` FOREIGN KEY (`student_id`) REFERENCES `students` (`id`) ON DELETE CASCADE,
  CONSTRAINT `fk_pf_subject` FOREIGN KEY (`subject_id`) REFERENCES `subjects` (`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci;
